export const CAREERS_BY_ID: Record<string, CareerDef> = Object.fromEntries(
  CAREERS.map(c => [c.id, c]),
);

/** Доход на конкретной ступени (1-based). */
export function careerIncomeAt(careerId: string, level: number): number {
  const c = CAREERS_BY_ID[careerId];
  if (!c) return 0;
  const idx = Math.max(0, Math.min(8, level - 1));
  return Math.round(c.baseIncome * c.levelMultipliers[idx]);
}